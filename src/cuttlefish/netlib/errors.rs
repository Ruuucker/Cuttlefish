pub fn LinuxCodeToLinuxError (errorCode: i64) -> LinuxError {
   match errorCode {
        -1 => LinuxError::PermissionDenied,
        -2 => LinuxError::NoSuchFileOrDirectory,
        //-3 => LinuxError::NoSuchProcess,
        // -3 => "No such process"),
        // -4 => "Interrupted system call"),
        // -5 => "I/O error"),
        // -6 => "No such device or address"),
        // -7 => "Argument list too long"),
        // -8 => "Exec format error"),
        //-9 => "Bad file number"),
        -9 => LinuxError::BadFileNumber,
        // -10 =>("No child processes"),
        -11 => LinuxError::TryAgain,
        // -12 =>("Out of memory"),
        // -13 =>("Permission denied"),
        // -14 =>("Bad address"),
        // -15 =>("Block device required"),
        // -16 =>("Device or resource busy"),
        // -17 =>("File exsits"),
        // -18 =>("Cross-device link"),
        // -19 =>("No such device"),
        // -20 =>("Not a directory"),
        // -21 =>("Is a directory"),
        // -22 =>("Invalid argument"),
        // -23 =>("File table overflow"),
        -24 => LinuxError::TooManyOpenFiles,
        -32 => LinuxError::BrokenPipe,
        -111 => LinuxError::ConnectionRefused,
        _ => panic!("Unknown error code {:}", errorCode)
   }
}

